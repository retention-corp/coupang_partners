#!/usr/bin/env bash
set -euo pipefail

PROJECT_ID="${PROJECT_ID:-retn-kr-website}"
REGION="${REGION:-us-central1}"
SERVICE_NAME="${SERVICE_NAME:-a-retn-shortener-ops}"
PUBLIC_BASE_URL="${PUBLIC_BASE_URL:-https://a.retn.kr}"
MIN_INSTANCES="${MIN_INSTANCES:-0}"
MAX_INSTANCES="${MAX_INSTANCES:-1}"
RUN_SMOKE_TEST_AFTER_DEPLOY="${RUN_SMOKE_TEST_AFTER_DEPLOY:-true}"
SMOKE_TEST_REQUIRE_AUTH="${SMOKE_TEST_REQUIRE_AUTH:-true}"
OPERATOR_CLIENT_ALLOWLIST="${OPERATOR_CLIENT_ALLOWLIST:-openclaw-skill,local-cli,smoke-test,coupang-mcp-fallback,shopping-ops}"
RATE_LIMIT_REQUESTS_PUBLIC="${RATE_LIMIT_REQUESTS_PUBLIC:-5}"
RATE_LIMIT_WINDOW_SECONDS_PUBLIC="${RATE_LIMIT_WINDOW_SECONDS_PUBLIC:-60}"
RATE_LIMIT_REQUESTS_AUTH="${RATE_LIMIT_REQUESTS_AUTH:-20}"
RATE_LIMIT_WINDOW_SECONDS_AUTH="${RATE_LIMIT_WINDOW_SECONDS_AUTH:-60}"
RATE_LIMIT_REQUESTS_ADMIN="${RATE_LIMIT_REQUESTS_ADMIN:-20}"
RATE_LIMIT_WINDOW_SECONDS_ADMIN="${RATE_LIMIT_WINDOW_SECONDS_ADMIN:-60}"

gcloud run deploy "${SERVICE_NAME}" \
  --project "${PROJECT_ID}" \
  --region "${REGION}" \
  --source . \
  --allow-unauthenticated \
  --set-secrets "COUPANG_ACCESS_KEY=coupang-access-key:latest,COUPANG_SECRET_KEY=coupang-secret-key:latest,OPENCLAW_SHOPPING_API_TOKENS=openclaw-shopping-api-token:latest,NLK_API_KEY=nl-go-kr-cert-key:latest,SASEO_API_KEY=nl-go-kr-cert-key:latest" \
  --set-env-vars "^|^GOOGLE_CLOUD_PROJECT=${PROJECT_ID}|OPENCLAW_SHOPPING_SHORTENER=firestore|OPENCLAW_SHORT_LINKS_COLLECTION=short_links|OPENCLAW_SHOPPING_ANALYTICS_PROVIDER=firestore|OPENCLAW_ANALYTICS_COLLECTION_PREFIX=shopping|OPENCLAW_SHOPPING_PUBLIC_BASE_URL=${PUBLIC_BASE_URL}|OPENCLAW_SHOPPING_ENABLE_OPERATOR_ROUTES=true|OPENCLAW_SHOPPING_CLIENT_ALLOWLIST_ENABLED=true|OPENCLAW_SHOPPING_CLIENT_ALLOWLIST=${OPERATOR_CLIENT_ALLOWLIST}|OPENCLAW_SHOPPING_RATE_LIMIT_REQUESTS_PUBLIC=${RATE_LIMIT_REQUESTS_PUBLIC}|OPENCLAW_SHOPPING_RATE_LIMIT_WINDOW_SECONDS_PUBLIC=${RATE_LIMIT_WINDOW_SECONDS_PUBLIC}|OPENCLAW_SHOPPING_RATE_LIMIT_REQUESTS_AUTH=${RATE_LIMIT_REQUESTS_AUTH}|OPENCLAW_SHOPPING_RATE_LIMIT_WINDOW_SECONDS_AUTH=${RATE_LIMIT_WINDOW_SECONDS_AUTH}|OPENCLAW_SHOPPING_RATE_LIMIT_REQUESTS_ADMIN=${RATE_LIMIT_REQUESTS_ADMIN}|OPENCLAW_SHOPPING_RATE_LIMIT_WINDOW_SECONDS_ADMIN=${RATE_LIMIT_WINDOW_SECONDS_ADMIN}|OPENCLAW_SHOPPING_RESPONSE_CACHE_TTL_SECONDS=900|COUPANG_PARTNERS_FALLBACK_AFFILIATE_TAG=AF3727577|COUPANG_PARTNERS_FALLBACK_AFFILIATE_ENABLED=true|COUPANG_UPSTREAM_RATE_LIMIT_ENABLED=true|COUPANG_UPSTREAM_LIMIT_ALL_PER_MINUTE=30|COUPANG_UPSTREAM_LIMIT_SEARCH_PER_MINUTE=15|COUPANG_UPSTREAM_LIMIT_DEEPLINK_PER_MINUTE=15|COUPANG_UPSTREAM_LIMIT_REPORT_PER_HOUR=150|COUPANG_UPSTREAM_COOLDOWN_SECONDS=300" \
  --memory 512Mi \
  --cpu 1 \
  --min-instances "${MIN_INSTANCES}" \
  --max-instances "${MAX_INSTANCES}" \
  --timeout 60 \
  "$@"

service_url="$(
  gcloud run services describe "${SERVICE_NAME}" \
    --project "${PROJECT_ID}" \
    --region "${REGION}" \
    --format='value(status.url)'
)"

echo "Operator service URL: ${service_url}"

if [[ "${RUN_SMOKE_TEST_AFTER_DEPLOY}" == "true" ]]; then
  if [[ -z "${OPENCLAW_SHOPPING_API_TOKEN:-}" ]]; then
    export OPENCLAW_SHOPPING_API_TOKEN="$(
      gcloud secrets versions access latest \
        --secret=openclaw-shopping-api-token \
        --project "${PROJECT_ID}"
    )"
  fi

  smoke_args=(
    scripts/smoke_test_hosted_backend.py
    --base-url "${service_url}"
    --allow-any-https-host
  )
  if [[ "${SMOKE_TEST_REQUIRE_AUTH}" == "true" ]]; then
    smoke_args+=(--require-auth)
  fi
  python3 "${smoke_args[@]}"
fi
